# Register appendix of the manual (A_registers.md), generated from the LiteDSP block registry:
#
#   python3 doc/manual/registers.py           write doc/manual/A_registers.md
#   python3 doc/manual/registers.py --check   fail if A_registers.md is not up to date
#
# The registry (litedsp/flow/registry.py) reflects every block with its registers enabled
# (litedsp/flow/metadata.py): pure Python (Migen elaboration), no Verilog and no FPGA toolchain.
# LiteDSP blocks are placed in user SoCs or flow netlists, so there is no fixed SoC to elaborate:
# the kit's tools/csr_doc.py (snapshots of elaborated SoCs) is not used by this manual. Register
# descriptions live in the block sources (CSRStorage/CSRStatus descriptions) and in the generated
# datasheets of doc/blocks/ (python3 -m litedsp.flow.docgen), which this appendix links.

import argparse
import os
import sys

HERE      = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
APPENDIX  = os.path.join(HERE, "A_registers.md")
BLOCKS    = "https://github.com/enjoy-digital/litedsp/blob/main/doc/blocks"

# Families in the order of the manual: (registry category, title, anchor of the chapter).
FAMILIES = [
    ("generation", "Signal generation",          "generation-mixing"),
    ("mixing",     "Mixing",                     "generation-mixing"),
    ("correction", "Impairment correction",      "generation-mixing"),
    ("filter",     "Filtering",                  "filters-rate"),
    ("rate",       "Rate conversion",            "filters-rate"),
    ("level",      "Level control",              "level-analysis"),
    ("analysis",   "Analysis and measurement",   "level-analysis"),
    ("comm",       "Communications",             "comm"),
    ("stream",     "Stream utilities and links", "stream-frontend"),
    ("motor",      "Motor control",              "motor"),
    ("audio",      "Audio",                      "audio"),
    ("radar",      "Radar and sonar",            "radar"),
    ("image",      "Image and video",            "image"),
]

ACCESS = {"read-write": "rw", "read-only": "ro"}

INTRO = """\
<!-- Generated by doc/manual/registers.py from the block registry: do not edit, edit the register
     descriptions in the block sources and regenerate (python3 doc/manual/registers.py). -->

# Register reference {#registers}

This appendix lists the registers of every block of the registry, one table per family. A block
exposes them when it is built with `with_csr=True` (see [the block contract](#architecture)); each
block has its own register bank, named after the block instance in the SoC or in the flow netlist.
The tables are generated from the registry reflection (`litedsp/flow/metadata.py`), which builds
each block with its registry defaults: a register that depends on a constructor parameter is
listed as it exists with these defaults, and its width follows that parameter.

Each register is given as `name`, access and width: access is `rw` for a register written by
software (`CSRStorage`) and `ro` for a status read by software (`CSRStatus`); the width is in bits.
A register wider than the CSR data width (32 bits by default) takes several consecutive words. The
offsets of the registers in a bank, and the base of each bank, depend on the build: they are in
the `csr.csv`, `csr.json` and `csr.h` files written by the build or by `litedsp_gen`, and the host
drivers access the registers by name. The datasheet of each block (linked from its name) gives the
description, reset value and fields of each register.
"""


def generate():
    sys.path.insert(0, REPO_ROOT)
    from litedsp.flow.registry import by_category

    cats  = by_category()
    known = {f[0] for f in FAMILIES}
    extra = sorted(set(cats) - known)
    if extra:
        raise SystemExit(f"registers.py: unknown registry categories {extra}: add them to FAMILIES")

    # Short global labels of the reference-style links (r1, r2, ...), in the order of the appendix.
    labels = {}
    def label(s):
        return labels.setdefault(s.key, f"r{len(labels) + 1}")

    out = [INTRO]
    for cat, title, chapter in FAMILIES:
        specs     = sorted(cats.get(cat, []), key=lambda s: s.display_name.lower())
        with_regs = [s for s in specs if s.csrs]
        without   = [s for s in specs if not s.csrs]
        nregs     = sum(len(s.csrs) for s in specs)
        out.append(f"## {title} {{#reg-{cat}}}\n")
        out.append(f"{len(specs)} blocks of `litedsp/{cat}/`, {nregs} registers; the blocks are "
                   f"described in [their chapter](#{chapter}).\n")
        if with_regs:
            out.append("| Block | Registers |")
            out.append("|----------------------------|--------------------------------------------------------|")
            for s in with_regs:
                regs = ", ".join(f"`{c.name}` {ACCESS.get(c.access, 'wo')} {c.size}" for c in s.csrs)
                name = s.display_name.replace("|", "/").replace("\u2014", "-")
                out.append(f"| [{name}][{label(s)}] | {regs} |")
            out.append("")
        if without:
            names = ", ".join(f"[{s.display_name}][{label(s)}]" for s in without)
            out.append(f"Without registers: {names}.\n")
        # Reference-style links: a URL in a table cell would be one unbreakable word.
        for s in specs:
            out.append(f"[{label(s)}]: {BLOCKS}/{s.key}.md")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main():
    parser = argparse.ArgumentParser(description="Generate the register appendix of the LiteDSP manual.")
    parser.add_argument("--check", action="store_true", help="Fail if A_registers.md is not up to date.")
    args = parser.parse_args()
    text = generate()
    if args.check:
        current = open(APPENDIX, encoding="utf-8").read() if os.path.exists(APPENDIX) else ""
        if current != text:
            print("STALE: doc/manual/A_registers.md (run python3 doc/manual/registers.py)")
            return 1
        print("doc/manual/A_registers.md is up to date")
        return 0
    with open(APPENDIX, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote doc/manual/A_registers.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())

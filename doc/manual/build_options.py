# Block parameter tables of the build options appendix (B_build_options.md), generated from the
# LiteDSP block registry:
#
#   python3 doc/manual/build_options.py           update B_build_options.md
#   python3 doc/manual/build_options.py --check   fail if B_build_options.md is not up to date
#
# Only the text between the BEGIN and END markers of B_build_options.md is generated; the rest of
# the appendix is written by hand. The registry (litedsp/flow/registry.py) reflects every block
# (litedsp/flow/metadata.py): pure Python, no Verilog and no FPGA toolchain.

import argparse
import inspect
import os
import sys

HERE      = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
APPENDIX  = os.path.join(HERE, "B_build_options.md")
BEGIN     = "<!-- BEGIN generated by doc/manual/build_options.py: do not edit, regenerate. -->"
END       = "<!-- END generated by doc/manual/build_options.py -->"

sys.path.insert(0, HERE)
from registers import FAMILIES  # noqa: E402  Same families and order as the register appendix.

INTRO = """\
## Block parameters {#opt-blocks}

The tables below list the constructor parameters of every block of the registry, one table per
family, as `name`=default. Each block is named by its registry key, the `type` of a netlist
block, followed by its display name.

The default shown is the one the flow uses for a netlist block. It is the registry value when the
registry sets one, in bold when it differs from the default of the Python constructor, and the
constructor default otherwise. A parameter shown without a value has no default and must be
given.

A long list default is summarized by its length. The possible values of a string parameter
follow it in parentheses. To keep the tables short, `data_width`=16 and `with_irq`=False are left
out where they are the default of the block: a block that lists no `data_width` takes 16-bit
samples.

`with_csr` is left out: it defaults to `True` in every block that takes it (some blocks have no
register even then, see [Register reference](#registers)). The chain builder passes its own value
([Chain builder](#tool-builder)): `True` for a standalone core, `False` for `litedsp_flow`
without `--csr`. The datasheet of each block, `doc/blocks/<key>.md` in
the repository ([catalogue](https://github.com/enjoy-digital/litedsp/blob/main/doc/blocks/index.md)),
describes each parameter; [Register reference](#registers) lists the registers.
"""


def fmt_value(value):
    if isinstance(value, (list, tuple)):
        text = repr(list(value))
        return text if len(text) <= 14 else f"list of {len(value)}"
    if isinstance(value, str):
        return value
    return repr(value)


# Parameters left out of the tables when they hold this default (stated in INTRO).
SHARED_DEFAULTS = {"data_width": 16, "with_irq": False}


def is_shared_default(spec, param, signature):
    if param.name not in SHARED_DEFAULTS or param.choices:
        return False
    p = signature.get(param.name)
    if p is None or p.default is inspect.Parameter.empty or p.default != SHARED_DEFAULTS[param.name]:
        return False
    return spec.kwargs.get(param.name, p.default) == SHARED_DEFAULTS[param.name]


def fmt_param(spec, param, signature):
    p = signature.get(param.name)
    has_ctor_default = p is not None and p.default is not inspect.Parameter.empty
    if param.default is None and not has_ctor_default and param.name not in spec.kwargs:
        text = f"`{param.name}`"
    else:
        text = f"`{param.name}`={fmt_value(param.default)}"
        if param.name in spec.kwargs and (not has_ctor_default or p.default != spec.kwargs[param.name]):
            text = f"**{text}**"
    if param.choices:
        text += " (" + ", ".join(str(c) for c in param.choices) + ")"
    return text


def generate_section():
    sys.path.insert(0, REPO_ROOT)
    from litedsp.flow.metadata import _real_init
    from litedsp.flow.registry import by_category

    cats  = by_category()
    known = {f[0] for f in FAMILIES}
    extra = sorted(set(cats) - known)
    if extra:
        raise SystemExit(f"build_options.py: unknown registry categories {extra}: add them to registers.FAMILIES")

    out = [BEGIN, "", INTRO]
    for cat, title, chapter in FAMILIES:
        specs = sorted(cats.get(cat, []), key=lambda s: s.display_name.lower())
        out.append(f"### {title} {{#opt-{cat}}}\n")
        out.append(f"{len(specs)} blocks of `litedsp/{cat}/`, described in [their chapter](#{chapter}).\n")
        out.append("| Block | Parameters |")
        out.append("|--------------------------------------------|----------------------------------------------------|")
        for s in specs:
            signature = inspect.signature(_real_init(s.cls)).parameters
            params    = [fmt_param(s, p, signature) for p in s.params
                         if not is_shared_default(s, p, signature)]
            name      = s.display_name.replace("|", "/").replace(" -> ", " to ")
            out.append(f"| `{s.key}` {name} | {', '.join(params) or 'none'} |")
        out.append("")
    out.append(END)
    return "\n".join(out)


def updated(text):
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < 0 or end < start:
        raise SystemExit("build_options.py: generated-section markers not found in B_build_options.md")
    return text[:start] + generate_section() + text[end + len(END):]


def main():
    parser = argparse.ArgumentParser(description="Generate the block parameter tables of the LiteDSP manual.")
    parser.add_argument("--check", action="store_true", help="Fail if B_build_options.md is not up to date.")
    args = parser.parse_args()
    current = open(APPENDIX, encoding="utf-8").read()
    text    = updated(current)
    if args.check:
        if current != text:
            print("STALE: doc/manual/B_build_options.md (run python3 doc/manual/build_options.py)")
            return 1
        print("doc/manual/B_build_options.md is up to date")
        return 0
    with open(APPENDIX, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote doc/manual/B_build_options.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
